#!/usr/bin/env bash
set -e
mkdir -p docs
cat > docs/release-note.md <<'MDEOF'
# 결제 모듈 v3.2.1 변경 사항

이번 문서에서는 결제 모듈 v3.2.1의 변경 사항을 살펴보겠습니다.

## 주요 변경

- 결제 승인 API의 평균 응답 시간이 340ms에서 120ms로 단축되었습니다 — 커넥션 풀 크기를 10에서 40으로 늘린 결과입니다.
- 카드사 점검 시간에는 결제 요청이 자동으로 재시도되어집니다.
- 부분 환불 처리 로직이 개선되어 환불 실패율이 줄어들 것으로 판단되어집니다.

## 참고

결론적으로 운영팀은 배포 후 30분간 결제 실패율을 모니터링해야 합니다 – 실패율이 1%를 넘으면 v3.2.0으로 롤백합니다.
MDEOF
