#!/usr/bin/env bash
# technical-writing 스캔. 사용: bash scan.sh <파일>
# [Layer 1]은 전수 제거 대상, [원칙 7]은 읽고 판단할 후보다.
F="$1"
if [ -z "$F" ] || [ ! -f "$F" ]; then
  echo "사용: bash scan.sh <파일>" >&2
  exit 2
fi

echo "=== [Layer 1] 기계 스캔 ==="
echo "--- em/en dash ---";  grep -n -e '—' -e '–' "$F"
echo "--- 이중피동 ---";     grep -nE '되어[지집]|보여[지집]|불려[지집]|쓰여[지집]|잊혀[지집]|나뉘어[지집]|여겨[지집]' "$F"
echo "--- 곡선따옴표 ---";   grep -n -e '“' -e '”' -e '‘' -e '’' "$F"
echo "--- 메타 담화 ---";    grep -nE '결론적으로|요약하면|앞서 (설명|말씀)|아시다시피|본질적으로|시사하는 바|(살펴|알아)보겠습니다' "$F"
echo "--- 번역투 조사 ---";  grep -nE '에 대[해한]|에 있어|에 의(해|한)|에서의|으로의|에의' "$F"

echo "=== [원칙 7] 실측 신호 후보 ==="
echo "--- 대구 (A가 아니라 B) ---";  grep -nE '(이|가) 아니라|것이 아니라|[가-힣]+인가, [가-힣]+인가' "$F"
echo "--- 연결어미 뒤 쉼표 ---";    grep -nE '[가-힣](고|며|지만|면서|아서|어서),' "$F"
echo "--- ~적 N ---";              grep -noE '[가-힣]+적 [가-힣]+' "$F"

exit 0
